"""Configuration A: ONLY the ORIGINAL vendor single-bin likelihood.

This entry point refuses configuration-B/multi-bin/provisional-halo-response
artifacts, then calls the existing APE adapter which delegates directly to
the unmodified original vendor calc_max_lkl and stats.log_likelihood.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from ape_post_lpsd.ape_max_likelihood import main as _vendor_adapter_main


class ConfigurationAInputError(ValueError):
    """Incorrect response boundary; do not mix A and B inputs."""


def validate_a_response_file(path):
    src = Path(path).expanduser().resolve()
    if not src.is_file():
        raise ConfigurationAInputError(f"APE response NPZ not found: {src}")
    try:
        with np.load(src, allow_pickle=False) as z:
            if set(z.files) != {
                "frequency_hz", "peak_norm_x", "peak_norm_y", "metadata_json"
            }:
                raise ConfigurationAInputError("Unexpected response NPZ schema")
            metadata = json.loads(str(z["metadata_json"].item()))
    except (OSError, ValueError, TypeError, KeyError, json.JSONDecodeError) as err:
        raise ConfigurationAInputError(f"Invalid Configuration A response: {err}") from err
    if not isinstance(metadata, dict) or metadata.get("configuration") != "A_original_vendor_single_bin":
        raise ConfigurationAInputError(
            "Refusing a response not generated by Configuration A.build_response"
        )
    if metadata.get("physical_upper_limits_authorized") is not False:
        raise ConfigurationAInputError("Unexpected scientific authorization metadata")
    if metadata.get("mu_definition") != "mu=(g_a_gamma_gamma/reference_coupling_gev_inv)^2":
        raise ConfigurationAInputError("Unexpected coupling definition")
    if metadata.get("spectral_shape_convention") != (
        "original-vendor single-bin peak_shape=[1], PSD per unit time variance"
    ):
        raise ConfigurationAInputError("Refusing multi-bin/halo response convention")
    return metadata


def main():
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--response-npz", required=True)
    args, _ = parser.parse_known_args()
    validate_a_response_file(args.response_npz)
    _vendor_adapter_main()


if __name__ == "__main__":
    main()
